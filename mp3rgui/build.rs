use std::path::{Path, PathBuf};

fn main() {
    #[cfg(windows)]
    {
        let mut res = winresource::WindowsResource::new();
        res.set_icon("icons/icon.ico");
        res.compile().unwrap();
    }

    let manifest_dir = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").unwrap());
    let po_dir = manifest_dir.join("locales");
    std::fs::create_dir_all(&po_dir).unwrap();
    println!("cargo:rerun-if-changed={}", po_dir.display());

    let out_dir = PathBuf::from(std::env::var("OUT_DIR").unwrap()).join("locale");
    std::fs::create_dir_all(&out_dir).unwrap();
    include_po::generate_locales_from_dir(&po_dir, out_dir.join("translators.rs")).unwrap();
    emit_catalogues(&po_dir, &out_dir.join("catalogues.rs"));
}

/// Lists the `.po` catalogues and a lookup of each language's own name.
/// `include-po` lowercases the module (`pt_BR.po` becomes `pt_br`) and does
/// not expose the list, so the Language menu needs this beside it.
fn emit_catalogues(po_dir: &Path, out_path: &Path) {
    let mut codes: Vec<String> = std::fs::read_dir(po_dir)
        .unwrap()
        .filter_map(|entry| {
            let path = entry.ok()?.path();
            if path.extension().and_then(|ext| ext.to_str()) != Some("po") {
                return None;
            }
            let stem = path.file_stem()?.to_str()?.to_string();
            stem.chars()
                .all(|c| c.is_ascii_alphanumeric() || c == '_')
                .then_some(stem)
        })
        .collect();
    codes.sort();

    let mut body = String::from(
        "// Generated by build.rs. Do not edit.\n\
         pub const CATALOGUES: &[&str] = &[\n",
    );
    for code in &codes {
        body.push_str(&format!("    \"{code}\",\n"));
    }
    body.push_str(
        "];\n\n#[allow(clippy::match_single_binding)]\n\
         pub fn native_name(code: &str) -> String {\n",
    );
    body.push_str("    let key = code.replace('-', \"_\").to_ascii_lowercase();\n");
    body.push_str("    match key.as_str() {\n");
    for code in &codes {
        let module = code.to_ascii_lowercase();
        body.push_str(&format!(
            "        \"{module}\" => ::tr::Translator::translate(\n\
             \x20           &translators::{module}::Translator,\n\
             \x20           \"English\",\n\
             \x20           Some(\"language name\"),\n\
             \x20       )\n\
             \x20       .into_owned(),\n"
        ));
    }
    body.push_str("        _ => code.to_string(),\n    }\n}\n");
    std::fs::write(out_path, body).unwrap();
}
